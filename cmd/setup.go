package cmd

// setup.go — "setup" subcommand: install udev rules for non-root device access.

import (
	"fmt"
	"os"
	"os/exec"
	"os/user"
	"path/filepath"
	"strings"

	"github.com/aic0d3r/z13ctl-plus/internal/cli"

	"github.com/spf13/cobra"
)

const rulesPath = "/etc/udev/rules.d/99-z13ctl-plus.rules"

var legacyPowerRulePaths = []string{
	"/etc/udev/rules.d/99-z13-power.rules",
	"/usr/lib/udev/rules.d/99-z13-power.rules",
}

const servicePath = "/etc/systemd/system/z13ctl-plus-perms.service"

var (
	setupGroup    string
	permsOnlyFlag bool
)

func buildRulesContent(group string) string {
	return fmt.Sprintf(`# 99-z13ctl-plus.rules — z13ctl-plus ASUS ROG Flow Z13 device access
#
# Grants members of the %s group read/write access to:
#   - ASUS HID devices used for keyboard and lightbar RGB control
#   - asus-wmi platform-profile attribute for performance profile control
#   - asus-nb-wmi battery charge_control_end_threshold for battery limit control
#   - Armoury Crate button input device for daemon button watcher
#   - asus-armoury firmware-attributes (boot_sound, panel_overdrive)
#   - hwmon fan curve attributes (asus_custom_fan_curve + asus pwm_enable)
#   - asus-nb-wmi PPT power limit attributes for TDP control
#   - the built-in USB camera's authorized attribute for the camera switch
#
# Generated by: z13ctl-plus setup
# To remove: sudo rm /etc/udev/rules.d/99-z13ctl-plus.rules && sudo udevadm control --reload-rules
SUBSYSTEM=="hidraw", ATTRS{idVendor}=="0b05", ATTRS{idProduct}=="18c6", MODE="0660", GROUP="%s"
SUBSYSTEM=="hidraw", ATTRS{idVendor}=="0b05", ATTRS{idProduct}=="1a30", MODE="0660", GROUP="%s"
ACTION=="add", SUBSYSTEM=="platform-profile", RUN+="/usr/bin/chgrp %s /sys%%p/profile", RUN+="/usr/bin/chmod g+w /sys%%p/profile"
ACTION=="add", SUBSYSTEM=="platform-profile", KERNELS=="asus-nb-wmi", RUN+="/usr/bin/chgrp %s /sys/class/power_supply/BAT0/charge_control_end_threshold", RUN+="/usr/bin/chmod g+w /sys/class/power_supply/BAT0/charge_control_end_threshold"
ACTION=="add", SUBSYSTEM=="input", KERNEL=="event*", ATTRS{name}=="Asus WMI hotkeys", MODE="0660", GROUP="%s"
ACTION=="add", SUBSYSTEM=="firmware-attributes", KERNEL=="asus-armoury", RUN+="/usr/bin/chgrp %s /sys/class/firmware-attributes/asus-armoury/attributes/boot_sound/current_value", RUN+="/usr/bin/chmod g+w /sys/class/firmware-attributes/asus-armoury/attributes/boot_sound/current_value"
ACTION=="add", SUBSYSTEM=="firmware-attributes", KERNEL=="asus-armoury", RUN+="/usr/bin/chgrp %s /sys/class/firmware-attributes/asus-armoury/attributes/panel_overdrive/current_value", RUN+="/usr/bin/chmod g+w /sys/class/firmware-attributes/asus-armoury/attributes/panel_overdrive/current_value"
ACTION=="add", SUBSYSTEM=="hwmon", ATTR{name}=="asus_custom_fan_curve", RUN+="/bin/sh -c 'chgrp %s /sys%%p/pwm*; chmod g+w /sys%%p/pwm*'"
ACTION=="add", SUBSYSTEM=="hwmon", ATTR{name}=="asus", RUN+="/bin/sh -c 'for f in /sys%%p/pwm*_enable; do [ -e \"$$f\" ] && chgrp %s \"$$f\" && chmod g+w \"$$f\"; done'"
ACTION=="add", SUBSYSTEM=="platform", KERNEL=="asus-nb-wmi", RUN+="/bin/sh -c 'for f in /sys/devices/platform/asus-nb-wmi/ppt_*; do [ -e \"$$f\" ] && chgrp %s \"$$f\" && chmod g+w \"$$f\"; done'"
ACTION=="add", SUBSYSTEM=="usb", ENV{DEVTYPE}=="usb_device", ATTR{removable}=="fixed", ATTR{product}=="*[Ww]ebcam*|*[Cc]amera*", RUN+="/usr/bin/chgrp %s /sys%%p/authorized", RUN+="/usr/bin/chmod g+w /sys%%p/authorized"
`, group, group, group, group, group, group, group, group, group, group, group, group)
}

// buildServiceContent generates the z13ctl-plus-perms.service unit file content.
// Handles sysfs files that cannot be set by udev rules:
//   - charge_control_end_threshold: created late in asus_nb_wmi probe()
//   - firmware-attributes current_value: may be created after parent ADD event
//   - PPT and CPU controls: may appear after their parent device events
//   - ryzen_smu_drv files: kobject under /sys/kernel/, not a udev device
func buildServiceContent(group string) string {
	return fmt.Sprintf(`[Unit]
Description=z13ctl-plus sysfs permissions (battery + firmware-attributes + PPT + CPU power + ryzen_smu)
# charge_control_end_threshold on BAT0 is created by asus_nb_wmi late in probe(),
# after all observable udev child-device events. udev RUN+= cannot catch it.
# firmware-attributes current_value files may be created after the parent ADD event.
# PPT attributes may be created too late for the asus-nb-wmi ADD rule.
# ryzen_smu files are under /sys/kernel/, not a udev subsystem.
After=sysinit.target

[Service]
Type=oneshot
RemainAfterExit=yes
ExecStart=/bin/sh -c 'for f in /sys/class/power_supply/BAT*/charge_control_end_threshold; do [ -e "$$f" ] && chgrp %s "$$f" && chmod g+w "$$f"; done || true'
ExecStart=/bin/sh -c 'for f in /sys/class/firmware-attributes/asus-armoury/attributes/boot_sound/current_value /sys/class/firmware-attributes/asus-armoury/attributes/panel_overdrive/current_value; do [ -e "$$f" ] && chgrp %s "$$f" && chmod g+w "$$f"; done || true'
ExecStart=/bin/sh -c 'for f in /sys/devices/platform/asus-nb-wmi/ppt_*; do [ -e "$$f" ] && chgrp %s "$$f" && chmod g+w "$$f"; done || true'
ExecStart=/bin/sh -c 'for f in /sys/devices/system/cpu/cpufreq/boost /sys/devices/system/cpu/cpufreq/policy*/scaling_min_freq /sys/devices/system/cpu/cpufreq/policy*/energy_performance_preference; do [ -e "$$f" ] && chgrp %s "$$f" && chmod g+w "$$f"; done || true'
ExecStart=/bin/sh -c 'for f in /sys/kernel/ryzen_smu_drv/smu_args /sys/kernel/ryzen_smu_drv/mp1_smu_cmd /sys/kernel/ryzen_smu_drv/rsmu_cmd; do [ -e "$$f" ] && chgrp %s "$$f" && chmod g+w "$$f" || true; done'

[Install]
WantedBy=multi-user.target
`, group, group, group, group, group)
}

// applySysfsPerms scans live sysfs for files managed by z13ctl-plus and either
// applies chgrp/chmod immediately (dryRun=false) or prints what would be done
// (dryRun=true). Missing paths are skipped; failures on existing paths are
// printed and counted, and returned as an error so setup cannot report
// success while nothing was granted.
func applySysfsPerms(group string, dryRun bool) error {
	failures := 0
	chgrpChmod := func(path, mode string) {
		if dryRun {
			fmt.Printf("  chgrp %s %s && chmod %s %s\n", group, path, mode, path)
			return
		}
		if err := exec.Command("chgrp", group, path).Run(); err != nil {
			failures++
			fmt.Fprintf(os.Stderr, "  chgrp failed: %s: %v\n", path, err)
			return
		}
		if err := exec.Command("chmod", mode, path).Run(); err != nil {
			failures++
			fmt.Fprintf(os.Stderr, "  chmod failed: %s: %v\n", path, err)
		}
	}
	applyMatches := func(pattern, mode string) {
		matches, _ := filepath.Glob(pattern)
		for _, path := range matches {
			chgrpChmod(path, mode)
		}
	}

	for _, pattern := range []string{
		"/sys/class/platform-profile/*/profile",
		"/sys/class/power_supply/*/charge_control_end_threshold",
		"/sys/class/firmware-attributes/asus-armoury/attributes/boot_sound/current_value",
		"/sys/class/firmware-attributes/asus-armoury/attributes/panel_overdrive/current_value",
	} {
		applyMatches(pattern, "g+w")
	}

	// hwmon permissions depend on the device name.
	hwmonDirs, _ := filepath.Glob("/sys/class/hwmon/*")
	for _, dir := range hwmonDirs {
		nameBytes, err := os.ReadFile(dir + "/name")
		if err != nil {
			continue
		}
		switch strings.TrimSpace(string(nameBytes)) {
		case "asus_custom_fan_curve":
			applyMatches(dir+"/pwm*", "g+w")
		case "asus":
			applyMatches(dir+"/pwm*_enable", "g+w")
		}
	}

	for _, pattern := range []string{
		"/sys/devices/platform/asus-nb-wmi/ppt_*",
		"/sys/devices/system/cpu/cpufreq/boost",
		"/sys/devices/system/cpu/cpufreq/policy*/scaling_min_freq",
		"/sys/devices/system/cpu/cpufreq/policy*/energy_performance_preference",
		"/sys/kernel/ryzen_smu_drv/smu_args",
		"/sys/kernel/ryzen_smu_drv/mp1_smu_cmd",
		"/sys/kernel/ryzen_smu_drv/rsmu_cmd",
	} {
		applyMatches(pattern, "g+w")
	}

	if path := cli.FindCameraPath(); path != "" {
		chgrpChmod(path, "g+w")
	}

	// Scan for the Armoury Crate button input device (Asus WMI hotkeys).
	inputDirs, _ := filepath.Glob("/sys/class/input/*")
	for _, dir := range inputDirs {
		nameBytes, err := os.ReadFile(dir + "/device/name")
		if err == nil && strings.TrimSpace(string(nameBytes)) == "Asus WMI hotkeys" {
			chgrpChmod("/dev/input/"+filepath.Base(dir), "g+rw")
		}
	}
	if failures > 0 {
		return fmt.Errorf("%d permission change(s) failed", failures)
	}
	return nil
}

var setupCmd = &cobra.Command{
	Use:   "setup",
	Short: "Install udev rules and boot service for non-root device access",
	Long: `Writes ` + rulesPath + ` granting members of a group read/write
access to the ASUS HID devices used for RGB control, the asus-wmi
platform-profile attribute for performance profile switching, the ACPI
battery charge threshold for battery limit control, the Armoury Crate
button input device for the daemon button watcher, asus-armoury
firmware-attributes (boot sound, panel overdrive), hwmon fan curve
attributes, and asus-nb-wmi PPT power limit attributes for TDP control.
Then reloads and triggers udev so the rules take effect immediately.

Also installs ` + servicePath + `, a small systemd oneshot that
runs 'chgrp' and 'chmod g+w' on the battery charge threshold attribute at boot.
This is required because the attribute is created late in the asus_nb_wmi kernel
driver's probe() sequence, after all udev events have already fired.

Use --perms-only to skip writing the rules file and only reapply sysfs
permissions (useful after a group change or kernel module reload).

Use --dry-run to preview exactly what would be written and which sysfs files
would be chmod'd, without making any changes (no root required).

This command must be run with sudo (unless --dry-run is used).`,
	RunE: func(_ *cobra.Command, _ []string) error {
		if dryRunFlag {
			if permsOnlyFlag {
				fmt.Println("=== DRY RUN: would reapply sysfs permissions ===")
			} else {
				fmt.Println("=== DRY RUN (no changes will be made) ===")
				fmt.Printf("\nWould write %s:\n\n", rulesPath)
				fmt.Print(buildRulesContent(setupGroup))
				fmt.Println("Would run: udevadm control --reload-rules")
				for _, path := range legacyPowerRulePaths {
					fmt.Printf("Would remove obsolete power policy rule if present: %s\n", path)
				}
				fmt.Println("Would run: udevadm trigger --subsystem-match=hidraw")
				fmt.Printf("\nWould write %s:\n\n", servicePath)
				fmt.Print(buildServiceContent(setupGroup))
				fmt.Println("Would run: systemctl daemon-reload")
				fmt.Println("Would run: systemctl enable --now z13ctl-plus-perms.service")
			}
			fmt.Println("\nWould apply sysfs permissions (files present on this system):")
			_ = applySysfsPerms(setupGroup, true)
			return nil
		}

		if os.Getuid() != 0 {
			return fmt.Errorf("this command requires root — run with sudo:\n  sudo z13ctl-plus setup\n\nTo preview changes without root: z13ctl-plus --dry-run setup")
		}

		if _, err := user.LookupGroup(setupGroup); err != nil {
			return fmt.Errorf("unknown group %q: %w\n  create it first or pass an existing group via --group", setupGroup, err)
		}
		if setupGroup == "users" || setupGroup == "wheel" {
			fmt.Fprintf(os.Stderr, "warning: group %q usually has many members; each one gains write access to power, fan and voltage controls. Consider a dedicated group via --group.\n", setupGroup)
		}

		// --perms-only: just reapply sysfs permissions, skip rules and service.
		if permsOnlyFlag {
			if err := applySysfsPerms(setupGroup, false); err != nil {
				return fmt.Errorf("applying sysfs permissions: %w", err)
			}
			fmt.Println("Applied sysfs permissions.")
			return nil
		}

		content := buildRulesContent(setupGroup)
		if err := os.WriteFile(rulesPath, []byte(content), 0o644); err != nil {
			return fmt.Errorf("write %s: %w", rulesPath, err)
		}
		fmt.Printf("Wrote %s (group: %s)\n", rulesPath, setupGroup)
		for _, path := range legacyPowerRulePaths {
			if err := os.Remove(path); err == nil {
				fmt.Printf("Removed obsolete power policy rule %s\n", path)
			} else if !os.IsNotExist(err) {
				return fmt.Errorf("remove obsolete rule %s: %w", path, err)
			}
		}

		if out, err := exec.Command("udevadm", "control", "--reload-rules").CombinedOutput(); err != nil {
			return fmt.Errorf("udevadm control --reload-rules: %w\n%s", err, out)
		}
		fmt.Println("Reloaded udev rules.")

		if out, err := exec.Command("udevadm", "trigger", "--subsystem-match=hidraw").CombinedOutput(); err != nil {
			return fmt.Errorf("udevadm trigger: %w\n%s", err, out)
		}
		fmt.Println("Triggered udev rules.")

		// systemd 259+ does not execute RUN{program} for synthetic udevadm trigger
		// events, so apply sysfs permissions directly. The udev rules cover
		// subsequent boots via real kernel ADD events.
		if err := applySysfsPerms(setupGroup, false); err != nil {
			return fmt.Errorf("applying sysfs permissions: %w", err)
		}
		fmt.Println("Applied sysfs permissions.")

		// Install the battery permissions service. charge_control_end_threshold is
		// created late in asus_nb_wmi probe(), after all udev events have fired, so
		// udev RUN+= cannot set its permissions reliably at boot.
		svcContent := buildServiceContent(setupGroup)
		if err := os.WriteFile(servicePath, []byte(svcContent), 0o644); err != nil {
			return fmt.Errorf("write %s: %w", servicePath, err)
		}
		fmt.Printf("Wrote %s\n", servicePath)
		if out, err := exec.Command("systemctl", "daemon-reload").CombinedOutput(); err != nil {
			fmt.Fprintf(os.Stderr, "note: systemctl daemon-reload failed: %v\n%s", err, out)
			fmt.Fprintf(os.Stderr, "Enable the service manually: sudo systemctl enable --now z13ctl-plus-perms.service\n")
		} else if out, err := exec.Command("systemctl", "enable", "--now", "z13ctl-plus-perms.service").CombinedOutput(); err != nil {
			fmt.Fprintf(os.Stderr, "note: systemctl enable failed: %v\n%s", err, out)
			fmt.Fprintf(os.Stderr, "Enable the service manually: sudo systemctl enable --now z13ctl-plus-perms.service\n")
		} else {
			fmt.Println("Enabled z13ctl-plus-perms.service.")
		}

		fmt.Printf("\nDone. Members of the '%s' group can now run z13ctl-plus without sudo.\n", setupGroup)
		fmt.Println("This covers RGB control, performance profiles, battery charge limiting,")
		fmt.Println("the Armoury Crate button, boot sound, panel overdrive, fan curves, TDP,")
		fmt.Println("and undervolt (if ryzen_smu is installed).")
		fmt.Printf("If your user is not in '%s', add it with:\n", setupGroup)
		fmt.Printf("  sudo usermod -aG %s $USER\n", setupGroup)
		fmt.Println("Then log out and back in for the group change to take effect.")
		return nil
	},
}

func init() {
	setupCmd.Flags().StringVar(&setupGroup, "group", "users", "Group to grant access to the ASUS HID devices")
	setupCmd.Flags().BoolVar(&permsOnlyFlag, "perms-only", false, "Reapply sysfs permissions without writing udev rules or service")
	rootCmd.AddCommand(setupCmd)
}
