package cmd

// setup.go — "setup" subcommand: install udev rules for non-root device access.
//
// permissionTargets is the single list of files z13ctl-plus needs write
// access to. setup applies it directly; the boot service and the udev rules
// both run `z13ctl-plus setup --perms-only`, so all three grant the same set.

import (
	"bufio"
	"fmt"
	"io/fs"
	"os"
	"os/exec"
	"os/user"
	"path/filepath"
	"regexp"
	"strconv"
	"strings"

	"github.com/aic0d3r/z13ctl-plus/internal/cli"

	"github.com/spf13/cobra"
)

const (
	rulesPath      = "/etc/udev/rules.d/99-z13ctl-plus.rules"
	servicePath    = "/etc/systemd/system/z13ctl-plus-perms.service"
	packagedBinary = "/usr/bin/z13ctl-plus"
	smuDir         = "/sys/kernel/ryzen_smu_drv"
)

// setupConfPath is a variable so tests can redirect it.
var setupConfPath = "/etc/z13ctl-plus/setup.conf"

var legacyPowerRulePaths = []string{
	"/etc/udev/rules.d/99-z13-power.rules",
	"/usr/lib/udev/rules.d/99-z13-power.rules",
}

var (
	setupGroup     string
	setupUndervolt bool
	permsOnlyFlag  bool
)

// setupConfig is what setup remembers between runs, so the boot service, the
// udev rules and package upgrades reapply the user's choices.
type setupConfig struct {
	Group     string
	Undervolt bool // grant raw ryzen_smu command access (opt-in)
}

func buildRulesContent(group, binary string) string {
	return fmt.Sprintf(`# 99-z13ctl-plus.rules — z13ctl-plus ASUS ROG Flow Z13 device access
#
# Device nodes (HID RGB devices, Armoury Crate button) get group %[1]s here.
# sysfs attributes (profile, battery limit, firmware attributes, fans, PPT,
# camera, CPU power, opt-in ryzen_smu) are granted by "z13ctl-plus setup
# --perms-only", run on each relevant device or module add event and by
# z13ctl-plus-perms.service at boot, using the group saved in
# /etc/z13ctl-plus/setup.conf.
#
# Generated by: z13ctl-plus setup
# To use a different group, run: sudo z13ctl-plus setup --group=<group>
SUBSYSTEM=="hidraw", ATTRS{idVendor}=="0b05", ATTRS{idProduct}=="18c6", MODE="0660", GROUP="%[1]s"
SUBSYSTEM=="hidraw", ATTRS{idVendor}=="0b05", ATTRS{idProduct}=="1a30", MODE="0660", GROUP="%[1]s"
ACTION=="add", SUBSYSTEM=="input", KERNEL=="event*", ATTRS{name}=="Asus WMI hotkeys", MODE="0660", GROUP="%[1]s"
ACTION=="add", SUBSYSTEM=="platform-profile", RUN+="%[2]s setup --perms-only"
ACTION=="add", SUBSYSTEM=="platform", KERNEL=="asus-nb-wmi", RUN+="%[2]s setup --perms-only"
ACTION=="add", SUBSYSTEM=="power_supply", KERNEL=="BAT*", RUN+="%[2]s setup --perms-only"
ACTION=="add", SUBSYSTEM=="firmware-attributes", KERNEL=="asus-armoury", RUN+="%[2]s setup --perms-only"
ACTION=="add", SUBSYSTEM=="hwmon", ATTR{name}=="asus_custom_fan_curve|asus", RUN+="%[2]s setup --perms-only"
ACTION=="add", SUBSYSTEM=="usb", ENV{DEVTYPE}=="usb_device", ATTR{removable}=="fixed", ATTR{product}=="*[Ww]ebcam*|*[Cc]amera*", RUN+="%[2]s setup --perms-only"
ACTION=="add", SUBSYSTEM=="module", KERNEL=="ryzen_smu|amd_pstate|asus_armoury|asus_nb_wmi", RUN+="%[2]s setup --perms-only"
`, group, binary)
}

// buildServiceContent generates z13ctl-plus-perms.service. It covers sysfs
// files created after every observable udev event (the battery threshold late
// in asus_nb_wmi probe, firmware-attributes values, PPT, cpufreq).
func buildServiceContent(binary string) string {
	return fmt.Sprintf(`[Unit]
Description=z13ctl-plus sysfs permissions
# Some attributes appear after every udev event that could grant them
# (charge_control_end_threshold late in asus_nb_wmi probe, PPT, cpufreq),
# so apply the full list once the system is up.
After=sysinit.target systemd-modules-load.service

[Service]
Type=oneshot
RemainAfterExit=yes
ExecStart=%s setup --perms-only

[Install]
WantedBy=multi-user.target
`, binary)
}

// installedBinary is the path written into the rules and boot service.
func installedBinary() string {
	if path, err := exec.LookPath("z13ctl-plus"); err == nil {
		if abs, absErr := filepath.Abs(path); absErr == nil {
			return abs
		}
	}
	if exe, err := os.Executable(); err == nil {
		return exe
	}
	return packagedBinary
}

var rulesGroupRe = regexp.MustCompile(`GROUP="([^"]+)"`)

// loadSetupConfig reads the saved choices. Without a saved file (first run
// of this version) it keeps what an earlier setup granted: the group from the
// installed rules and SMU access if it is currently group-writable.
func loadSetupConfig() (cfg setupConfig, saved bool) {
	cfg = setupConfig{Group: "users"}
	f, err := os.Open(setupConfPath)
	if err != nil {
		for _, path := range []string{rulesPath, "/usr/lib/udev/rules.d/99-z13ctl-plus.rules"} {
			if data, readErr := os.ReadFile(path); readErr == nil {
				if m := rulesGroupRe.FindSubmatch(data); m != nil {
					cfg.Group = string(m[1])
					break
				}
			}
		}
		if fi, statErr := os.Stat(smuDir + "/mp1_smu_cmd"); statErr == nil {
			cfg.Undervolt = fi.Mode().Perm()&0o020 != 0
		}
		return cfg, false
	}
	defer func() { _ = f.Close() }()
	scanner := bufio.NewScanner(f)
	for scanner.Scan() {
		key, value, ok := strings.Cut(strings.TrimSpace(scanner.Text()), "=")
		if !ok || strings.HasPrefix(key, "#") {
			continue
		}
		switch strings.TrimSpace(key) {
		case "group":
			cfg.Group = strings.TrimSpace(value)
		case "undervolt":
			cfg.Undervolt, _ = strconv.ParseBool(strings.TrimSpace(value))
		}
	}
	return cfg, true
}

func saveSetupConfig(cfg setupConfig) error {
	if err := os.MkdirAll(filepath.Dir(setupConfPath), 0o755); err != nil {
		return err
	}
	content := fmt.Sprintf("# Written by z13ctl-plus setup; read by setup --perms-only (boot service, udev).\ngroup=%s\nundervolt=%t\n",
		cfg.Group, cfg.Undervolt)
	return os.WriteFile(setupConfPath, []byte(content), 0o644)
}

// permTarget is one file z13ctl-plus needs access to, with the mode bits the
// group gets (0o020 = g+w; 0o060 = g+rw for device nodes).
type permTarget struct {
	Path string
	Bits fs.FileMode
}

// permissionTargets lists every existing file z13ctl-plus writes. Raw
// ryzen_smu command files are included only with undervolt: any group member
// could send arbitrary SMU commands through them, bypassing the -40 cap.
func permissionTargets(undervolt bool) []permTarget {
	var targets []permTarget
	add := func(bits fs.FileMode, patterns ...string) {
		for _, pattern := range patterns {
			matches, _ := filepath.Glob(pattern)
			for _, path := range matches {
				targets = append(targets, permTarget{path, bits})
			}
		}
	}
	add(0o020,
		"/sys/class/platform-profile/*/profile",
		"/sys/class/power_supply/*/charge_control_end_threshold",
		"/sys/class/firmware-attributes/asus-armoury/attributes/boot_sound/current_value",
		"/sys/class/firmware-attributes/asus-armoury/attributes/panel_overdrive/current_value",
		"/sys/devices/platform/asus-nb-wmi/ppt_*",
		"/sys/devices/system/cpu/cpufreq/boost",
		"/sys/devices/system/cpu/cpufreq/policy*/scaling_min_freq",
		"/sys/devices/system/cpu/cpufreq/policy*/energy_performance_preference",
	)
	// hwmon numbers are unstable; match by device name.
	hwmonDirs, _ := filepath.Glob("/sys/class/hwmon/*")
	for _, dir := range hwmonDirs {
		nameBytes, err := os.ReadFile(dir + "/name")
		if err != nil {
			continue
		}
		switch strings.TrimSpace(string(nameBytes)) {
		case "asus_custom_fan_curve":
			add(0o020, dir+"/pwm*")
		case "asus":
			add(0o020, dir+"/pwm*_enable")
		}
	}
	if undervolt {
		add(0o020, smuDir+"/smu_args", smuDir+"/mp1_smu_cmd")
	}
	if path := cli.FindCameraPath(); path != "" {
		targets = append(targets, permTarget{path, 0o020})
	}
	// Armoury Crate button input device (Asus WMI hotkeys).
	inputDirs, _ := filepath.Glob("/sys/class/input/*")
	for _, dir := range inputDirs {
		nameBytes, err := os.ReadFile(dir + "/device/name")
		if err == nil && strings.TrimSpace(string(nameBytes)) == "Asus WMI hotkeys" {
			add(0o060, "/dev/input/"+filepath.Base(dir))
		}
	}
	return targets
}

// applySysfsPerms grants group access to every permission target, or prints
// what it would do (dryRun). Without undervolt it also removes group write
// from the raw SMU files a previous version granted. Failures on existing
// paths are printed, counted and returned so setup cannot report success
// while nothing was granted.
func applySysfsPerms(group string, undervolt, dryRun bool) error {
	if dryRun {
		for _, t := range permissionTargets(undervolt) {
			fmt.Printf("  chgrp %s %s && chmod g+%s %s\n", group, t.Path, modeLetters(t.Bits), t.Path)
		}
		if !undervolt {
			fmt.Printf("  chmod g-w %s/{smu_args,mp1_smu_cmd} (undervolt not enabled)\n", smuDir)
		}
		return nil
	}
	g, err := user.LookupGroup(group)
	if err != nil {
		return fmt.Errorf("unknown group %q: %w", group, err)
	}
	gid, _ := strconv.Atoi(g.Gid)
	failures := 0
	for _, t := range permissionTargets(undervolt) {
		fi, statErr := os.Stat(t.Path)
		if statErr != nil {
			continue // vanished since the scan
		}
		if chErr := os.Chown(t.Path, -1, gid); chErr != nil {
			failures++
			fmt.Fprintf(os.Stderr, "  chgrp failed: %s: %v\n", t.Path, chErr)
			continue
		}
		if chErr := os.Chmod(t.Path, fi.Mode().Perm()|t.Bits); chErr != nil {
			failures++
			fmt.Fprintf(os.Stderr, "  chmod failed: %s: %v\n", t.Path, chErr)
		}
	}
	if !undervolt {
		for _, path := range []string{smuDir + "/smu_args", smuDir + "/mp1_smu_cmd"} {
			if fi, statErr := os.Stat(path); statErr == nil && fi.Mode().Perm()&0o022 != 0 {
				if chErr := os.Chmod(path, fi.Mode().Perm()&^0o022); chErr != nil {
					failures++
					fmt.Fprintf(os.Stderr, "  chmod failed: %s: %v\n", path, chErr)
				}
			}
		}
	}
	if failures > 0 {
		return fmt.Errorf("%d permission change(s) failed", failures)
	}
	return nil
}

func modeLetters(bits fs.FileMode) string {
	if bits&0o040 != 0 {
		return "rw"
	}
	return "w"
}

var setupCmd = &cobra.Command{
	Use:   "setup",
	Short: "Install udev rules and boot service for non-root device access",
	Long: `Grants a group access to everything z13ctl-plus controls: the ASUS HID
RGB devices, the Armoury Crate button, platform profile, battery charge limit,
boot sound, panel overdrive, fan curves, TDP, CPU power and the camera switch.

Writes ` + rulesPath + ` and ` + servicePath + `,
applies the permissions immediately, and saves the chosen group and undervolt
choice in ` + setupConfPath + ` so later runs (boot, module loads,
package upgrades) keep them. Without --group, the saved group is reused
(default: users).

--undervolt also grants raw ryzen_smu command access, which undervolting
needs. Any member of the group can then send arbitrary SMU commands, so the
-40 Curve Optimizer limit only holds for z13ctl-plus itself. Use it with a
group only you belong to. --undervolt=false revokes it.

Use --perms-only to only reapply sysfs permissions (this is what the boot
service and udev rules run).

Use --dry-run to preview without changes (no root required).

This command must be run with sudo (unless --dry-run is used).`,
	RunE: func(cmd *cobra.Command, _ []string) error {
		cfg, saved := loadSetupConfig()
		if cmd.Flags().Changed("group") {
			cfg.Group = setupGroup
		}
		if cmd.Flags().Changed("undervolt") {
			cfg.Undervolt = setupUndervolt
		}
		binary := installedBinary()

		if dryRunFlag {
			if permsOnlyFlag {
				fmt.Println("=== DRY RUN: would reapply sysfs permissions ===")
			} else {
				fmt.Println("=== DRY RUN (no changes will be made) ===")
				fmt.Printf("\nWould write %s:\n\n", rulesPath)
				fmt.Print(buildRulesContent(cfg.Group, binary))
				fmt.Printf("\nWould write %s:\n\n", servicePath)
				fmt.Print(buildServiceContent(binary))
				fmt.Printf("\nWould save %s: group=%s undervolt=%t\n", setupConfPath, cfg.Group, cfg.Undervolt)
				fmt.Println("Would run: udevadm control --reload-rules")
				fmt.Println("Would run: udevadm trigger --subsystem-match=hidraw --subsystem-match=input")
				fmt.Println("Would run: systemctl daemon-reload && systemctl enable z13ctl-plus-perms.service")
			}
			fmt.Println("\nWould apply sysfs permissions (files present on this system):")
			return applySysfsPerms(cfg.Group, cfg.Undervolt, true)
		}

		if os.Getuid() != 0 {
			return fmt.Errorf("this command requires root — run with sudo:\n  sudo z13ctl-plus setup\n\nTo preview changes without root: z13ctl-plus --dry-run setup")
		}
		if _, err := user.LookupGroup(cfg.Group); err != nil {
			return fmt.Errorf("unknown group %q: %w\n  create it first or pass an existing group via --group", cfg.Group, err)
		}
		if !saved || cmd.Flags().Changed("group") || cmd.Flags().Changed("undervolt") || !permsOnlyFlag {
			if err := saveSetupConfig(cfg); err != nil {
				return fmt.Errorf("save %s: %w", setupConfPath, err)
			}
		}

		if permsOnlyFlag {
			if err := applySysfsPerms(cfg.Group, cfg.Undervolt, false); err != nil {
				return fmt.Errorf("applying sysfs permissions: %w", err)
			}
			fmt.Println("Applied sysfs permissions.")
			return nil
		}

		if cfg.Group == "users" || cfg.Group == "wheel" {
			fmt.Fprintf(os.Stderr, "note: group %q usually has many members; each one gains write access to power and fan controls. Consider a dedicated group via --group.\n", cfg.Group)
		}
		if err := os.WriteFile(rulesPath, []byte(buildRulesContent(cfg.Group, binary)), 0o644); err != nil {
			return fmt.Errorf("write %s: %w", rulesPath, err)
		}
		fmt.Printf("Wrote %s (group: %s)\n", rulesPath, cfg.Group)
		for _, path := range legacyPowerRulePaths {
			if err := os.Remove(path); err == nil {
				fmt.Printf("Removed obsolete power policy rule %s\n", path)
			} else if !os.IsNotExist(err) {
				return fmt.Errorf("remove obsolete rule %s: %w", path, err)
			}
		}

		if out, err := exec.Command("udevadm", "control", "--reload-rules").CombinedOutput(); err != nil {
			return fmt.Errorf("udevadm control --reload-rules: %w\n%s", err, out)
		}
		// MODE/GROUP assignments apply on synthetic events; RUN programs do
		// not (systemd 259+), so sysfs permissions are applied directly below.
		if out, err := exec.Command("udevadm", "trigger", "--subsystem-match=hidraw", "--subsystem-match=input").CombinedOutput(); err != nil {
			return fmt.Errorf("udevadm trigger: %w\n%s", err, out)
		}
		fmt.Println("Reloaded and triggered udev rules.")

		if err := applySysfsPerms(cfg.Group, cfg.Undervolt, false); err != nil {
			return fmt.Errorf("applying sysfs permissions: %w", err)
		}
		fmt.Println("Applied sysfs permissions.")

		if err := os.WriteFile(servicePath, []byte(buildServiceContent(binary)), 0o644); err != nil {
			return fmt.Errorf("write %s: %w", servicePath, err)
		}
		fmt.Printf("Wrote %s\n", servicePath)
		if out, err := exec.Command("systemctl", "daemon-reload").CombinedOutput(); err != nil {
			fmt.Fprintf(os.Stderr, "note: systemctl daemon-reload failed: %v\n%s", err, out)
			fmt.Fprintf(os.Stderr, "Enable the service manually: sudo systemctl enable z13ctl-plus-perms.service\n")
		} else if out, err := exec.Command("systemctl", "enable", "z13ctl-plus-perms.service").CombinedOutput(); err != nil {
			fmt.Fprintf(os.Stderr, "note: systemctl enable failed: %v\n%s", err, out)
			fmt.Fprintf(os.Stderr, "Enable the service manually: sudo systemctl enable z13ctl-plus-perms.service\n")
		} else {
			fmt.Println("Enabled z13ctl-plus-perms.service.")
		}

		fmt.Printf("\nDone. Members of the '%s' group can now run z13ctl-plus without sudo.\n", cfg.Group)
		if cfg.Undervolt {
			fmt.Println("Undervolt access (raw ryzen_smu) is granted to the group.")
		} else {
			fmt.Println("Undervolt is not enabled; run 'sudo z13ctl-plus setup --undervolt' to allow it.")
		}
		printGroupMembershipHint(cfg.Group)
		return nil
	},
}

// printGroupMembershipHint tells the invoking user (sudo's SUDO_USER) whether
// a group change and re-login are still needed.
func printGroupMembershipHint(group string) {
	name := os.Getenv("SUDO_USER")
	if name == "" {
		return
	}
	u, err := user.Lookup(name)
	if err != nil {
		return
	}
	g, err := user.LookupGroup(group)
	if err != nil {
		return
	}
	if gids, gidErr := u.GroupIds(); gidErr == nil {
		for _, gid := range gids {
			if gid == g.Gid {
				return
			}
		}
	}
	fmt.Printf("User %s is not in '%s'. Add it, then log out and back in:\n", name, group)
	fmt.Printf("  sudo usermod -aG %s %s\n", group, name)
}

func init() {
	setupCmd.Flags().StringVar(&setupGroup, "group", "users", "Group to grant access to (default: the saved group, else users)")
	setupCmd.Flags().BoolVar(&setupUndervolt, "undervolt", false, "Also grant raw ryzen_smu access for undervolting (default: the saved choice)")
	setupCmd.Flags().BoolVar(&permsOnlyFlag, "perms-only", false, "Only reapply sysfs permissions (used by the boot service and udev)")
	rootCmd.AddCommand(setupCmd)
}
